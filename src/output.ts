import type { OutputWriter } from './types.js';

export const ansi = {
  reset: '\x1b[0m',
  bold: '\x1b[1m',
  dim: '\x1b[2m',
  green: '\x1b[32m',
  yellow: '\x1b[33m',
  red: '\x1b[31m',
  cyan: '\x1b[36m',
} as const;

export function paint(value: string, color: keyof typeof ansi, enabled = true): string {
  return enabled ? `${ansi[color]}${value}${ansi.reset}` : value;
}

export function defaultWriter(): OutputWriter {
  return {
    write(message) {
      process.stdout.write(`${message}\n`);
    },
    error(message) {
      process.stderr.write(`${message}\n`);
    },
  };
}
