import { join } from 'node:path';
import { editText, insertBefore, writeGenerated } from '../files.js';
import { ensureSuffix, kebab } from '../names.js';
import type { PageGeneratorOptions } from '../interfaces/generators/page.js';

export type { PageGeneratorOptions };
export async function generatePage(
  options: PageGeneratorOptions,
): Promise<{ file: string; routePath: string; registered: boolean }> {
  const className = ensureSuffix(options.name, 'Page');
  const file = join(options.projectRoot, 'src/app', `${className}.tsx`);
  const routePath =
    options.path ?? (className === 'HomePage' ? '/' : `/${kebab(className.replace(/Page$/, ''))}`);

  const content = `import { Anchor } from '@newfoundcodes/helvetium-dom';

export function ${className}() {
  return (
    <main class="page">
      <h1>${className.replace(/Page$/, '')}</h1>
      <p>Generated by Helvetium CLI.</p>
      <Anchor to="/">Home</Anchor>
    </main>
  );
}\n`;
  await writeGenerated(file, content, options.force ?? false, options.dryRun ?? false);

  let registered = false;
  if (options.register !== false) {
    const routes = join(options.projectRoot, 'src/app/routes.ts');
    registered = await editText(
      routes,
      (source) => {
        if (
          source.includes(`component: ${className}`) ||
          source.includes(`'${routePath}'`) ||
          source.includes(`"${routePath}"`)
        ) {
          throw new Error(`A page route already exists for ${className} or ${routePath}`);
        }

        let next = insertBefore(
          source,
          'export const pageRoutes',
          `import { ${className} } from './${className}.js';\n`,
        );

        const index = next.lastIndexOf('];');
        if (index < 0) {
          throw new Error('Could not find pageRoutes array terminator');
        }

        const route = `  {
    id: '${kebab(className.replace(/Page$/, ''))}',
    path: '${routePath}',
    component: ${className},
    title: '${options.title ?? className.replace(/Page$/, '')} - Helvetium'
  },\n`;
        next = `${next.slice(0, index)}${route}${next.slice(index)}`;
        return next;
      },
      options.dryRun ?? false,
    );
  }

  return { file, routePath, registered };
}
